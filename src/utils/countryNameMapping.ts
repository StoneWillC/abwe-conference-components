// Helper function to find country code from name
export const getCountryCodeFromName = (name: string): string | null => {
  const normalizedName = name.trim().toUpperCase();

  // Direct lookup
  if (countryNameToCode[normalizedName]) {
    return countryNameToCode[normalizedName];
  }

  // Try partial matches for common variations
  const partialMatches = Object.keys(countryNameToCode).filter(
    (key) => key.includes(normalizedName) || normalizedName.includes(key)
  );

  if (partialMatches.length === 1) {
    return countryNameToCode[partialMatches[0]];
  }

  return null;
};
